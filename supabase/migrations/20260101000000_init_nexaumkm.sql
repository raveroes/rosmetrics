-- ============================================================
--  0. TIPE ENUM  (MySQL ENUM -> PostgreSQL ENUM)
-- ============================================================
do $$ begin
  create type public.user_role as enum ('owner', 'employee');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.submission_status as enum ('draft', 'submitted', 'validated', 'rejected');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.factor_key as enum ('INS', 'OV', 'LDI', 'WEQ', 'OPS', 'ECT');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.validation_level as enum ('error', 'warning', 'info');
exception when duplicate_object then null; end $$;

-- ============================================================
--  Fungsi trigger pengganti "ON UPDATE CURRENT_TIMESTAMP" MySQL
-- ============================================================
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $fn$
begin
  new.updated_at = now();
  return new;
end;
$fn$;

-- ============================================================
--  1. TABEL USERS  (akun login owner & pegawai)
-- ============================================================
create table if not exists public.users (
  id            integer generated by default as identity primary key,
  umkm_name     varchar(150) not null,             -- Nama resmi bisnis / UMKM
  email         varchar(180) not null,             -- Email bisnis (unik)
  password_hash varchar(255) not null,             -- bcrypt hash
  role          public.user_role not null,         -- Peran responden
  lokasi        varchar(100),                      -- Provinsi / kota
  sektor        varchar(80),                       -- Bidang industri
  omzet         bigint check (omzet >= 0),         -- Omzet per bulan (IDR)
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint uq_email unique (email)
);
comment on table public.users is 'Akun pengguna RosMetrics (owner & pegawai)';

create index if not exists idx_users_role   on public.users (role);
create index if not exists idx_users_sektor on public.users (sektor);
-- Pencarian umkm_name tanpa peduli huruf besar/kecil (dipakai register & submit)
create index if not exists idx_users_umkm_lower on public.users (lower(trim(umkm_name)));

drop trigger if exists trg_users_updated_at on public.users;
create trigger trg_users_updated_at
  before update on public.users
  for each row execute function public.set_updated_at();

-- ============================================================
--  2. TABEL SUBMISSIONS  (satu baris = satu pengiriman formulir)
-- ============================================================
create table if not exists public.submissions (
  id              integer generated by default as identity primary key,
  user_id         integer not null,                -- FK -> users.id
  role            public.user_role not null,       -- Peran saat submit
  status          public.submission_status not null default 'submitted',
  validation_pass boolean not null default false,  -- true = lolos validasi backend
  submitted_at    timestamptz not null default now(),
  validated_at    timestamptz,
  notes           text,                            -- Catatan validator / admin

  -- Skor per faktor (dinormalisasi 0.0000-1.0000)
  score_ins       numeric(5,4),                    -- Sumber Daya  (owner)
  score_ov        numeric(5,4),                    -- Budaya       (employee)
  score_ldi       numeric(5,4),                    -- Kepemimpinan (employee)
  score_weq       numeric(5,4),                    -- Proses       (employee)
  score_ops       numeric(5,4),                    -- Inovasi      (owner)
  score_ect       numeric(5,4),                    -- Eksternal    (owner)
  score_composite numeric(5,4),                    -- Skor komposit tertimbang 0-1
  score_on_5      numeric(4,2),                    -- Skor komposit skala 0-5
  health_category varchar(30),                     -- SANGAT BAIK / BAIK / CUKUP / PERLU PERHATIAN

  constraint fk_sub_user foreign key (user_id)
    references public.users (id) on delete restrict on update cascade
);
comment on table public.submissions is 'Header setiap pengiriman formulir SiSEHAT';

create index if not exists idx_sub_user      on public.submissions (user_id);
create index if not exists idx_sub_status    on public.submissions (status);
create index if not exists idx_sub_submitted on public.submissions (submitted_at);
-- Index parsial: dashboard & daftar UMKM hanya membaca baris yang lolos validasi
create index if not exists idx_sub_valid on public.submissions (submitted_at) where validation_pass;

-- ============================================================
--  3. TABEL ANSWERS  (jawaban individual per pertanyaan)
-- ============================================================
create table if not exists public.answers (
  id            integer generated by default as identity primary key,
  submission_id integer not null,                  -- FK -> submissions.id
  factor_key    public.factor_key not null,        -- Faktor kesehatan
  question_id   varchar(20) not null,              -- ID soal: ins_oh1 ... weq_oh17
  question_code varchar(10) not null,              -- Kode codebook: OH-1 ... OH-35
  answer_value  smallint not null,                 -- Nilai jawaban (1-5 atau 1-3)
  scale_max     smallint not null,                 -- Batas atas skala (3 atau 5)
  constraint uq_sub_question unique (submission_id, question_id),
  constraint fk_ans_sub foreign key (submission_id)
    references public.submissions (id) on delete cascade on update cascade,
  constraint chk_answer_range check (answer_value >= 1 and answer_value <= scale_max)
);
comment on table public.answers is 'Jawaban per pertanyaan tiap submission';

create index if not exists idx_ans_factor on public.answers (factor_key);
create index if not exists idx_ans_qid    on public.answers (question_id);

-- ============================================================
--  4. TABEL VALIDATION_LOG  (log hasil validasi backend)
-- ============================================================
create table if not exists public.validation_log (
  id            integer generated by default as identity primary key,
  submission_id integer not null,
  level         public.validation_level not null,
  factor_key    varchar(10),
  field_name    varchar(30),
  error_code    varchar(40) not null,
  message       text not null,
  created_at    timestamptz not null default now(),
  constraint fk_vlog_sub foreign key (submission_id)
    references public.submissions (id) on delete cascade on update cascade
);
comment on table public.validation_log is 'Log error & warning dari proses validasi';

create index if not exists idx_vlog_sub   on public.validation_log (submission_id);
create index if not exists idx_vlog_level on public.validation_log (level);

