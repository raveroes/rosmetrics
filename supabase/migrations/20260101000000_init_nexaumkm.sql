-- ============================================================
--  7. VIEW — ringkasan skor per submission (untuk dashboard)
--     security_invoker: view tunduk pada RLS tabel dasarnya
-- ============================================================
create or replace view public.v_submission_summary
with (security_invoker = true) as
select
  s.id  as submission_id,
  u.id  as user_id,
  u.umkm_name,
  u.email,
  u.lokasi,
  u.sektor,
  s.role,
  s.status,
  s.validation_pass,
  s.submitted_at,
  s.score_ins,
  s.score_ov,
  s.score_ldi,
  s.score_weq,
  s.score_ops,
  s.score_ect,
  s.score_composite,
  s.score_on_5,
  s.health_category
from public.submissions s
join public.users u on u.id = s.user_id;

-- ============================================================
--  8. VIEW — rata-rata skor per faktor (untuk halaman Home)
-- ============================================================
create or replace view public.v_factor_averages
with (security_invoker = true) as
select
  round(avg(score_ins),       4) as avg_ins,
  round(avg(score_ov),        4) as avg_ov,
  round(avg(score_ldi),       4) as avg_ldi,
  round(avg(score_weq),       4) as avg_weq,
  round(avg(score_ops),       4) as avg_ops,
  round(avg(score_ect),       4) as avg_ect,
  round(avg(score_composite), 4) as avg_composite,
  count(*)                       as total_submissions
from public.submissions
where validation_pass;

-- ============================================================
--  9. KEAMANAN — RLS aktif, tanpa policy, cabut hak anon/authenticated
--     (Edge Function memakai koneksi database langsung, bukan Data API)
-- ============================================================
alter table public.users                enable row level security;
alter table public.submissions          enable row level security;
alter table public.answers              enable row level security;
alter table public.validation_log       enable row level security;
alter table public.factor_definitions   enable row level security;
alter table public.question_definitions enable row level security;

revoke all on table
  public.users, public.submissions, public.answers, public.validation_log,
  public.factor_definitions, public.question_definitions,
  public.v_submission_summary, public.v_factor_averages
from anon, authenticated;
